// 今月と来月の行事を、アイデア出しの材料として文章にする
export function seasonalContext(now = new Date(), extra = ""): string {
  const m = now.getMonth() + 1;
  const next = (m % 12) + 1;
  const date = `${now.getFullYear()}年${m}月${now.getDate()}日`;
  return [
    `今日は ${date}。`,
    `今月（${m}月）によくある話題: ${MONTHS[m].join("、")}`,
    `来月（${next}月）によくある話題: ${MONTHS[next].join("、")}`,
    extra.trim() ? `運営者が気になっている、いまの話題: ${extra.trim()}` : "",
    "tool は時期に合うと広まりやすいので、これから1〜2か月の話題に合うものを優先して考えてよい（ただし無理に合わせなくてよい）。開催日が年によって変わる行事の日付は断定しないこと。",
  ].filter(Boolean).join("\n");
}
